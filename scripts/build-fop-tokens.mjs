// Builds app/fop-tokens.css from the Friends of Pakistan design-system tokens.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TOKENS_PATH = path.join(
  root,
  'docs/design-system/friends-of-pakistan/project/tokens.json',
);
const OUT_PATH = path.join(root, 'app/fop-tokens.css');

const resolve = (v) => {
  const m = /^\{(.+)\}$/.exec(v);
  return m ? `var(--${m[1]})` : v;
};

const px = (v) => (typeof v === 'number' ? String(v) : v);

export function buildTokensCss(tokens) {
  const light = [];
  const dark = [];
  for (const t of tokens.color.tokens) {
    if (t.value && typeof t.value === 'object') {
      light.push(`  --${t.name}: ${resolve(t.value.light)};`);
      dark.push(`  --${t.name}: ${resolve(t.value.dark)};`);
    } else {
      light.push(`  --${t.name}: ${resolve(t.value)};`);
    }
  }
  for (const key of ['spacing', 'radius', 'shadow', 'borderWidth', 'opacity', 'zIndex', 'layout']) {
    for (const t of tokens[key].tokens) {
      light.push(`  --${t.name}: ${t.value};`);
    }
  }

  const out = [];
  out.push('/* Generated by scripts/build-fop-tokens.mjs from tokens.json. Do not edit. */');
  out.push(':root {', ...light, '}', '');
  out.push('[data-theme="dark"] {', ...dark, '}', '');
  for (const group of tokens.type.groups) {
    const family = group.name === 'Display' ? 'var(--font-serif)' : 'var(--font-sans)';
    for (const s of group.styles) {
      const lines = [
        `  font-family: ${family};`,
        `  font-size: ${s.fontSize};`,
        `  line-height: ${px(s.lineHeight)};`,
        `  font-weight: ${s.fontWeight};`,
      ];
      if (group.name === 'Labels' || s.name === 'heading-4') {
        lines.push('  text-transform: uppercase;');
      }
      out.push(`.t-${s.name} {`, ...lines, '}', '');
    }
  }
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const tokens = JSON.parse(readFileSync(TOKENS_PATH, 'utf8'));
  writeFileSync(OUT_PATH, buildTokensCss(tokens));
  console.log(`wrote ${path.relative(root, OUT_PATH)}`);
}
